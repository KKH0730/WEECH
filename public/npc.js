/* 들어올 때마다 다른 인사. 늘 같은 말이면 녹음기 같다. */
export function helloOf(npc) {
  const i = Math.floor(Math.random() * npc.hellos.length);
  return npc.hellos[i];
}

/* ---- 흐트러진 수 ---------------------------------------------------
 *  Math.random 을 쓰면 사람마다 다른 길을 걷는다. 씨앗과 번호만으로
 *  늘 같은 값이 나오는 해시를 쓴다. */
function hash(seed, n) {
  let h = (seed * 374761393 + n * 668265263) | 0;
  h = (h ^ (h >>> 13)) * 1274126177;
  h = h ^ (h >>> 16);
  return (h >>> 0) / 4294967296;
}

/* 트리와 선물 더미 — 걸어 들어가면 안 되는 자리 */
function blocked(x, z) {
  const T = R.XMAS && R.XMAS.tree;
  if (!T) return false;
  const keep = T.r * 1.35 + 0.5;                 // 선물까지 넉넉히 비켜 간다
  return (x - T.x) * (x - T.x) + (z - T.z) * (z - T.z) < keep * keep;
}

/* n번째 들를 자리. 막힌 데가 나오면 번호를 비틀어 다시 뽑는다 —
 * 비트는 방법이 정해져 있으므로 결과는 여전히 누구에게나 같다. */
function waypoint(npc, n) {
  for (let k = 0; k < 8; k++) {
    const a = hash(npc.seed, n * 7 + k * 101);
    const b = hash(npc.seed, n * 7 + k * 101 + 53);
    const x = YARD.x0 + a * (YARD.x1 - YARD.x0);
    const z = YARD.z0 + b * (YARD.z1 - YARD.z0);
    if (!blocked(x, z)) return { x: x, z: z };
  }
  return { x: 0, z: (YARD.z0 + YARD.z1) / 2 };   // 여덟 번 다 막히면 한가운데
}

/* -π ~ π 로 줄인 각도 차. 350° 돌지 말고 -10° 돌라는 뜻이다. */
function shortArc(d) {
  while (d > Math.PI) d -= Math.PI * 2;
  while (d < -Math.PI) d += Math.PI * 2;
  return d;
}
const ease = (p) => { const q = Math.min(1, Math.max(0, p)); return q * q * (3 - 2 * q); };

/* 서버시각 t(초)에 이 NPC 가 어디서 어느 쪽을 보고 있나.
 *   { x, z, yaw, walking, turning, stride } */
export function poseAt(npc, t) {
  const LEG = npc.leg, WALK = npc.walk, SPEED = npc.speed;
  const TURN = npc.turn;
  const leg = Math.floor(t / LEG);
  const u = t - leg * LEG;

  const prev = waypoint(npc, leg - 1);
  const from = waypoint(npc, leg);
  const to = waypoint(npc, leg + 1);
  const dx = to.x - from.x, dz = to.z - from.z;
  const dist = Math.hypot(dx, dz) || 1e-6;

  const yawIn = Math.atan2(from.x - prev.x, from.z - prev.z);   // 들어온 방향
  const yawGo = Math.atan2(dx, dz);                             // 나갈 방향

  /* 한 칸은 세 토막이다 — 제자리에서 돌고, 걷고, 서서 둘러본다.
   * 돌지 않고 바로 걸으면 몸이 옆으로 미끄러지는 것처럼 보인다. */
  const need = Math.min(WALK, dist / SPEED);    // 걷는 데 드는 시간

  if (u < TURN) {
    const e = ease(u / TURN);
    return {
      x: from.x, z: from.z,
      yaw: yawIn + shortArc(yawGo - yawIn) * e,
      walking: false, turning: true, stride: 0
    };
  }

  const v = u - TURN;
  if (v < need) {
    const e = ease(v / need);
    return {
      x: from.x + dx * e,
      z: from.z + dz * e,
      yaw: yawGo,
      walking: true, turning: false,
      // 걸음 박자 — 칸이 바뀌어도 이어지도록 시각에서 뽑는다
      stride: (t * SPEED * 3.1) % (Math.PI * 2)
    };
  }

  // 다 왔다 — 서서 천천히 두리번거린다
  return {
    x: to.x, z: to.z,
    yaw: yawGo + Math.sin((v - need) * 0.55) * 0.7,
    walking: false, turning: false, stride: 0
  };
}

