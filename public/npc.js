/* ------------------------------------------------------------------
 *  npc.js — 산타와 루돌프가 돌아다니고, 말을 건다
 *
 *  ── 어디 있는가 ──────────────────────────────────────────────
 *  NPC 자리를 서버가 들고 중계하면 사람 수만큼 쪽지가 늘어난다. 그렇다고
 *  각자 제멋대로 걷게 두면, 한 사람은 "산타 옆이야" 하는데 다른 사람 화면에선
 *  산타가 반대편에 있다.
 *
 *  그래서 자리를 '시각의 함수' 로 둔다. 같은 시각을 넣으면 누구 화면에서든
 *  같은 자리가 나온다 — 주고받는 쪽지는 0이고, 서버는 아무 일도 안 한다.
 *  시계는 방 정보에 실려 오는 serverNow 로 맞춘다.
 *
 *      자리 = poseAt(npc, 서버시각)
 *
 *  걸음은 한 다리(leg)를 일정한 시간 칸에 넣어 끊는다. 칸 길이가 고정이면
 *  지금이 몇 번째 다리인지 나눗셈 한 번으로 나온다 — 처음부터 더해 올 필요가
 *  없다. 각 칸은 '걷는 동안' 과 '서서 두리번거리는 동안' 으로 나뉜다.
 *
 *  ── 무엇을 아는가 ────────────────────────────────────────────
 *  묻는 말에 답하는 것은 미리 적어 둔 문답이다. 바깥 모델을 부르지 않는다 —
 *  이 저장소는 외부 패키지 0개이고, 서버는 쪽지만 중계한다.
 * ------------------------------------------------------------------ */
